#!/usr/bin/env bun
// Scans every sibling project's wrangler config (.toml / .jsonc / .json) at
// build time and emits src/infrastructure.generated.ts — a typed InfraGraph
// consumed by the cloud Worker. Local + plugin runtimes ignore this file
// and call the SSG daemon's /api/json/workspace/infrastructure endpoint.
//
// Helpers are exported so test/build-infrastructure.test.ts can drive each
// piece in isolation under Node (vitest's node env). Use fileURLToPath rather
// than the Bun-only `import.meta.dir` so the same module works under both
// runtimes.

import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { buildInfraGraph } from "./lib/build-infra-graph";
import {
  type ParsedWrangler,
  parseWranglerConfig,
  WRANGLER_FILENAMES,
} from "./lib/wrangler-parser";
import { PROJECTS_REGISTRY } from "./registry.generated";

const HERE = dirname(fileURLToPath(import.meta.url));
const WORKSPACE_ROOT = resolve(HERE, "..");
export const MONO_ROOT = resolve(WORKSPACE_ROOT, "..");
const OUT = join(HERE, "infrastructure.generated.ts");

export function findWranglerConfig(dir: string): string | null {
  for (const f of WRANGLER_FILENAMES) {
    const p = join(dir, f);
    if (existsSync(p)) return p;
  }
  return null;
}

export function listProjects(root: string): string[] {
  // Any sibling directory with a wrangler config — no name-prefix assumption,
  // so this stays correct if the monorepo grows worker dirs not named
  // "sigmashake-*".
  const entries = readdirSync(root);
  return entries
    .filter((name) => !name.startsWith(".") && name !== "node_modules")
    .filter((name) => {
      const dir = join(root, name);
      try {
        if (!statSync(dir).isDirectory()) return false;
      } catch {
        return false;
      }
      return findWranglerConfig(dir) !== null;
    })
    .sort();
}

export function descriptionFor(slug: string): string {
  const entry = PROJECTS_REGISTRY.find((p) => p.slug === slug);
  return entry?.description ?? "";
}

function main(): void {
  const slugs = listProjects(MONO_ROOT);
  const projectDescriptions = new Map<string, string>(
    slugs.map((slug) => [slug, descriptionFor(slug)]),
  );
  const parsed: ParsedWrangler[] = [];
  for (const slug of slugs) {
    const configPath = findWranglerConfig(join(MONO_ROOT, slug));
    if (!configPath) continue;
    const content = readFileSync(configPath, "utf8");
    const p = parseWranglerConfig(content, configPath);
    // The directory name is the authoritative slug; default the wrangler
    // `name` to it only when the config omits one.
    if (!p.name) p.name = slug;
    p.slug = slug;
    parsed.push(p);
  }

  const graph = buildInfraGraph(parsed, {
    projectDescriptions,
    root: "/registry",
  });

  const banner =
    "// AUTO-GENERATED by src/build-infrastructure.ts — do not edit.\n" +
    "// Re-run `bun run src/build-infrastructure.ts` or `bun run prebuild`.\n\n";
  const body =
    "import type {InfraGraph} from './types';\n\n" +
    "export const INFRASTRUCTURE_GRAPH: InfraGraph = " +
    JSON.stringify(graph, null, 2) +
    ";\n";
  writeFileSync(OUT, banner + body);
  console.log(
    `infrastructure: wrote ${graph.nodes.length} nodes / ${graph.edges.length} edges → src/infrastructure.generated.ts`,
  );
}

// Run main() only when executed directly (bun src/build-infrastructure.ts),
// not when the test suite imports the helpers above.
const executedDirectly =
  typeof process !== "undefined" &&
  Array.isArray(process.argv) &&
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (executedDirectly) {
  main();
}
